const fs=require('fs'),vm=require('vm'),assert=require('assert/strict');
const source=fs.readFileSync(require('path').join(__dirname,'../bridge/Export Cubis.js'),'utf8');
const context={get:(o,k)=>o&&o[k]};vm.createContext(context);
vm.runInContext(source.slice(source.indexOf('        function cubisEdgeDeduction('),source.indexOf('        var rows = []')),context);
const convert=context.cubisEdgeDeduction;
for(const [input,expected] of [[2,1.5],[0.8,0.3],[0.4,0.4],[1.5,1.5],[0.3,0.3],[1,1]])assert.equal(convert(input),expected);
const points=[[0,0],[100,0],[100,50],[0,50]];
const contour={Count:4,Min:{x:0,y:0},Max:{x:100,y:50},Objects:points.map((p,i)=>({IsLine:()=>true,AsLine:()=>({Pos1:{x:p[0],y:p[1]},Pos2:{x:points[(i+1)%4][0],y:points[(i+1)%4][1]}})}))};
const edges=[['X_min',2,50],['X_max',0.8,50],['Y_min',0.4,100]].map(([side,t,len])=>({latura_locala:side,grosime_mm:t,lungime_segment_mm:len,sub_taiere:true}));
const before=JSON.stringify(edges);
let result=context.cubisDimensions({Contour:contour},100,50,edges);
assert.equal(result.lungime_mm,98.2);assert.equal(result.latime_mm,49.6);
assert.equal(JSON.stringify(edges),before,'Physical thickness must remain unchanged');
edges[0].sub_taiere=false;
assert.equal(context.cubisDimensions({Contour:contour},100,50,edges).lungime_mm,99.7);
edges[0].sub_taiere=true;
result=context.cubisDimensions({Contour:{Count:6}},100,50,edges.concat([edges[0]]));
assert.equal(result.lungime_mm,98.2);assert.equal(result.latime_mm,49.6);
assert.equal(result.foloseste_gabarit,true);
console.log('PASS: Cubis deductions, unchanged physical thickness, ClipPanel and irregular contour');
